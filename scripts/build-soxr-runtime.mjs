function inside(root, target, label) {
  const rel = path.relative(root, target);
  if (rel === '' || rel === '..' || rel.startsWith(`..${path.sep}`) || path.isAbsolute(rel)) {
    throw new Error(`${label} escapes its authorized project directory: ${target}`);
  }
  return target;
}

function log(message) {
  process.stdout.write(`${message}\n`);
}

function run(command, args, { allowEmptyTarNameWarnings = false, ...options } = {}) {
  const result = spawnSync(command, args, {
    cwd: projectRoot,
    encoding: 'utf8',
    maxBuffer: 128 * 1024 * 1024,
    windowsHide: true,
    ...options,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    const lines = String(result.stderr ?? '').split(/\r?\n/).filter(Boolean);
    const expectedWarnings = allowEmptyTarNameWarnings && lines.length > 0 && lines.every((line) =>
      /Archive entry has empty or unreadable filename .*skipping|Error exit delayed from previous errors/i.test(line));
    if (expectedWarnings) {
      log(`tar.exe skipped empty PAX metadata entries in ${path.basename(args[1] ?? '')}`);
      return result.stdout ?? '';
    }
    throw new Error(`${command} ${args.join(' ')} failed (${result.status}):\n${result.stderr || result.stdout}`);
  }
  return result.stdout ?? '';
}

async function sha256File(filePath) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(filePath)) hash.update(chunk);
  return hash.digest('hex');
}

async function ensureDirectory(dir) {
  await fs.mkdir(dir, { recursive: true });
}

async function verifiedArchive() {
  const actual = await sha256File(archivePath);
  if (actual !== sourceArchiveSha256) {
    throw new Error(`Official SoXR source cache hash mismatch: ${actual}; expected ${sourceArchiveSha256}`);
  }
  return actual;
}

function validateArchivePath(raw) {
  const name = raw.replaceAll('\\', '/');
  if (name.includes('\0') || name.startsWith('/') || /^[A-Za-z]:/.test(name) || name.startsWith('//')) {
    throw new Error(`Unsafe SoXR source archive path: ${raw}`);
  }
  if (name.includes(':') || name.split('/').some((part) => part === '..')) {
    throw new Error(`Unsafe SoXR source archive path: ${raw}`);
  }
  return name;
}

function configText() {
  const entries = Object.entries(configMacros).map(([name, value]) => `#define ${name} ${value}`);
  return [
    '/* Generated by scripts/build-soxr-runtime.mjs from official SoXR 0.1.3 source. */',
    '/* Double-precision constant-rate engine only; no OpenMP or SIMD engines. */',
    '#if !defined soxr_config_included',
    '#define soxr_config_included',
    ...entries,
    '#endif',
    '',
  ].join('\n');
}

async function saveGeneratedConfig() {
  await ensureDirectory(generatedRoot);
  const expected = configText();
  try {
    const existing = await fs.readFile(generatedConfig, 'utf8');
    if (existing !== expected) {
      if (!existing.startsWith('/* Generated by scripts/build-soxr-runtime.mjs')) {
        throw new Error(`Refusing to overwrite a user-managed SoXR config: ${generatedConfig}`);
      }
      await fs.writeFile(generatedConfig, expected, 'utf8');
    }
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
    await fs.writeFile(generatedConfig, expected, { encoding: 'utf8', flag: 'wx' });
  }
  return createHash('sha256').update(expected).digest('hex');
}

async function existingSourceManifestMatches(archiveHash) {
  try {
    const sourceManifest = JSON.parse(await fs.readFile(sourceManifestPath, 'utf8'));
    if (sourceManifest.sourceArchiveSha256 !== archiveHash) return false;
    for (const entry of sourceManifest.upstreamFiles ?? []) {
      const filePath = inside(projectRoot, path.resolve(projectRoot, entry.path), 'source fingerprint');
      if ((await sha256File(filePath)) !== entry.sha256) return false;
    }
    return true;
  } catch (error) {
    if (error?.code === 'ENOENT') return false;
    throw error;
  }
}

async function stageUpstreamSource(archiveHash) {
  if (await existingSourceManifestMatches(archiveHash)) return JSON.parse(await fs.readFile(sourceManifestPath, 'utf8'));
  try {
    await fs.access(sourceRoot);
    throw new Error(`SoXR source directory exists without a matching source manifest; preserving it: ${sourceRoot}`);
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }

  const namesText = run('tar.exe', ['-tf', archivePath], { allowEmptyTarNameWarnings: true });
  const archiveNames = namesText.split(/\r?\n/).filter(Boolean).map(validateArchivePath);
  const prefix = `${versionRoot}/`;
  const selected = archiveNames.filter((name) => {
    if (name.endsWith('/')) return false;
    if (!name.startsWith(prefix)) return false;
    const rel = name.slice(prefix.length);
    return upstreamBuildFiles.has(rel) || (rel.startsWith('src/') && /\.(?:c|h)$/i.test(rel));
  });
  for (const rel of upstreamBuildFiles) {
    if (!selected.includes(`${prefix}${rel}`)) throw new Error(`Official SoXR source archive is missing ${rel}`);
  }
  if (!selected.includes(`${prefix}src/soxr.h`)) throw new Error('Official SoXR source archive is missing src/soxr.h');

  const verbose = run('tar.exe', ['-tvf', archivePath], { allowEmptyTarNameWarnings: true });
  const linkNames = new Set();
  for (const line of verbose.split(/\r?\n/).filter((line) => line.startsWith('l') || line.startsWith('h'))) {
    const beforeTarget = line.split(' -> ')[0].trim();
    const linkName = beforeTarget.split(/\s+/).at(-1)?.replaceAll('\\', '/');
    if (linkName) linkNames.add(linkName);
  }
  const selectedLink = selected.find((name) => linkNames.has(name));
  if (selectedLink) throw new Error(`Build input is a link instead of a regular source file: ${selectedLink}`);

  await ensureDirectory(sourceHome);
  run('tar.exe', ['-xf', archivePath, '-C', sourceHome, ...selected], { allowEmptyTarNameWarnings: true });
  const upstreamFiles = [];
  for (const archiveName of selected) {
    const relFromVersion = archiveName.slice(prefix.length);
    const sourceFile = path.join(sourceRoot, ...relFromVersion.split('/'));
    const relativeProjectPath = path.relative(projectRoot, sourceFile).split(path.sep).join('/');
    upstreamFiles.push({ path: relativeProjectPath, size: (await fs.stat(sourceFile)).size, sha256: await sha256File(sourceFile) });
  }
  upstreamFiles.sort((a, b) => a.path.localeCompare(b.path));
  const sourceManifest = {
    version: '0.1.3',
    sourceArchiveUrl,
    sourceArchiveSha256: archiveHash,
    upstreamFiles,
  };
  await fs.writeFile(sourceManifestPath, `${JSON.stringify(sourceManifest, null, 2)}\n`, { flag: 'wx' });
  return sourceManifest;
}

async function compilerVersion() {
  try {
    await fs.access(zigExe);
  } catch {
    throw new Error(`Approved Zig compiler not found at project path ${path.relative(projectRoot, zigExe)}`);
  }
  return run(zigExe, ['version']).trim();
}

function flags(sourceRootForIncludes, configDir) {
  return [
    'cc',
    '-target', 'x86_64-windows-gnu',
    '-shared',
    '-std=gnu89',
    '-O2',
    '-mno-avx',
    '-mno-avx2',
    '-mno-fma',
    '-fno-vectorize',
    '-fno-slp-vectorize',
    '-DSOXR_DLL',
    '-Dsoxr_EXPORTS',
    '-DSOXR_LIB',
    '-I', path.relative(projectRoot, path.join(sourceRootForIncludes, 'src')).split(path.sep).join('/'),
    '-I', path.relative(projectRoot, configDir).split(path.sep).join('/'),
  ];
}

function runtimeBuildFingerprint(sourceManifest, configHash, zigVersion, buildScriptHash) {
  const fingerprintPayload = {
    sourceArchiveSha256: sourceManifest.sourceArchiveSha256,
    upstreamFiles: sourceManifest.upstreamFiles,
    generatedConfigSha256: configHash,
    buildScriptSha256: buildScriptHash,
    compiler: { path: path.relative(projectRoot, zigExe).split(path.sep).join('/'), version: zigVersion },
    target: 'x86_64-windows-gnu',
    flags: flags(sourceRoot, generatedRoot),
    linkerFlags,
    sources: sourceFilesToCompile.map((file) => `vendor/audio/soxr/source/${versionRoot}/${file}`),
  };
  return createHash('sha256').update(JSON.stringify(fingerprintPayload)).digest('hex');
}

async function readBuildManifest() {
  try {
    return JSON.parse(await fs.readFile(buildManifestPath, 'utf8'));
  } catch (error) {
    if (error?.code === 'ENOENT') return null;
    throw error;
  }
}

async function compileDll(sourceManifest, configHash, zigVersion, fingerprint) {
  const oldBuild = await readBuildManifest();
  if (oldBuild?.buildFingerprint === fingerprint) {
    try {
      const existingHash = await sha256File(runtimeDll);
      if (existingHash === oldBuild.dllSha256) {
        log('Using previously built SoXR DLL with matching source and compiler fingerprints');
        return oldBuild;
      }
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error;
    }
  }

  await ensureDirectory(buildTempRoot);
  const zigCacheRoot = path.join(projectRoot, '.tools', 'zig-cache', 'soxr');
  const zigLocalCache = path.join(zigCacheRoot, 'local');
  const zigGlobalCache = path.join(zigCacheRoot, 'global');
  await ensureDirectory(zigLocalCache);
  await ensureDirectory(zigGlobalCache);
  const tempDll = path.join(buildTempRoot, `soxr-${process.pid}.dll`);
  const compileSources = sourceFilesToCompile.map((file) => path.join(sourceRoot, ...file.split('/')));
  const compileFlags = flags(sourceRoot, generatedRoot);
  const commandArgs = [...compileFlags, ...linkerFlags, '-o', tempDll, ...compileSources];
  log(`Building SoXR with Zig ${zigVersion}: ${path.relative(projectRoot, zigExe)}`);
  const buildResult = spawnSync(zigExe, commandArgs, {
    cwd: projectRoot,
    encoding: 'utf8',
    maxBuffer: 128 * 1024 * 1024,
    windowsHide: true,
    env: {
      ...process.env,
      ZIG_LOCAL_CACHE_DIR: zigLocalCache,
      ZIG_GLOBAL_CACHE_DIR: zigGlobalCache,
    },
  });
  if (buildResult.error) throw buildResult.error;
  if (buildResult.stdout) process.stdout.write(buildResult.stdout);
  if (buildResult.stderr) process.stderr.write(buildResult.stderr);
  if (buildResult.status !== 0) {
    await fs.rm(tempDll, { force: true }).catch(() => {});
    throw new Error(`Zig SoXR source build failed with exit code ${buildResult.status}`);
  }
  const builtHash = await sha256File(tempDll);
  const existingRuntimeHash = await fs.access(runtimeDll).then(() => sha256File(runtimeDll), (error) => {
    if (error?.code === 'ENOENT') return null;
    throw error;
  });
  if (existingRuntimeHash && existingRuntimeHash !== builtHash && existingRuntimeHash !== oldBuild?.dllSha256) {
    const backup = path.join(stagingRoot, 'legacy-conda-soxr.dll');
    await ensureDirectory(path.dirname(backup));
    try {
      const backupHash = await sha256File(backup);
      if (backupHash !== existingRuntimeHash) throw new Error(`Existing legacy SoXR backup differs; refusing overwrite: ${backup}`);
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error;
      await fs.copyFile(runtimeDll, backup);
    }
  }
  await ensureDirectory(runtimeRoot);
  await fs.copyFile(tempDll, runtimeDll);
  const publishedHash = await sha256File(runtimeDll);
  if (publishedHash !== builtHash) throw new Error(`Published SoXR DLL hash changed during copy: ${publishedHash}`);
  await fs.rm(tempDll, { force: true });

  const buildScriptPath = path.join(projectRoot, 'scripts', 'build-soxr-runtime.mjs');
  const sourceFiles = [...sourceManifest.upstreamFiles, {
    path: path.relative(projectRoot, generatedConfig).split(path.sep).join('/'),
    size: (await fs.stat(generatedConfig)).size,
    sha256: configHash,
  }, {
    path: path.relative(projectRoot, buildScriptPath).split(path.sep).join('/'),
    size: (await fs.stat(buildScriptPath)).size,
    sha256: await sha256File(buildScriptPath),
  }].sort((a, b) => a.path.localeCompare(b.path));
  const manifest = {
    version: '0.1.3',
    sourceArchiveUrl,
    sourceArchiveSha256: sourceManifest.sourceArchiveSha256,
    sourceFiles,
    generatedConfig: {
      path: path.relative(projectRoot, generatedConfig).split(path.sep).join('/'),
      sha256: configHash,
      macros: configMacros,
    },
    compiler: {
      name: 'Zig C compiler',
      path: path.relative(projectRoot, zigExe).split(path.sep).join('/'),
      version: zigVersion,
    },
    target: 'x86_64-windows-gnu',
    zigCacheDirectories: [
      path.relative(projectRoot, zigLocalCache).split(path.sep).join('/'),
      path.relative(projectRoot, zigGlobalCache).split(path.sep).join('/'),
    ],
    compileFlags: compileFlags.slice(1),
    linkerFlags,
    compiledSources: sourceFilesToCompile.map((file) => `vendor/audio/soxr/source/${versionRoot}/${file}`),
    engine: 'CR64 double constant-rate, scalar FFT4G64',
    openmp: false,
    simdEngines: false,
    buildFingerprint: fingerprint,
    dllPath: path.relative(projectRoot, runtimeDll).split(path.sep).join('/'),
    dllSha256: publishedHash,
    dllSize: (await fs.stat(runtimeDll)).size,
  };
  await fs.writeFile(buildManifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  log(`Built project-local SoXR DLL: ${path.relative(projectRoot, runtimeDll)} (${publishedHash})`);
  return manifest;
}

async function main() {
  const sourceOnly = process.argv.includes('--source-only');
  const archiveHash = await verifiedArchive();
  const sourceManifest = await stageUpstreamSource(archiveHash);
  const configHash = await saveGeneratedConfig();
  if (sourceOnly) {
    log(`Official SoXR 0.1.3 source and public header prepared under ${path.relative(projectRoot, sourceHome)}`);
    return;
  }
  const zigVersion = await compilerVersion();
  const buildScriptPath = path.join(projectRoot, 'scripts', 'build-soxr-runtime.mjs');
  const buildScriptHash = await sha256File(buildScriptPath);
  const fingerprint = runtimeBuildFingerprint(sourceManifest, configHash, zigVersion, buildScriptHash);
  const buildManifest = await compileDll(sourceManifest, configHash, zigVersion, fingerprint);
  log(JSON.stringify({ buildFingerprint: buildManifest.buildFingerprint, dllSha256: buildManifest.dllSha256 }));
}

main().catch((error) => {
  process.stderr.write(`build-soxr-runtime: ${error.stack || error}\n`);
  process.exitCode = 1;
});
