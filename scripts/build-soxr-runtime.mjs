const generatedConfig = path.join(generatedRoot, 'soxr-config.h');
const sourceManifestPath = path.join(projectRoot, 'vendor', 'audio', 'soxr', 'source-manifest.json');
const buildManifestPath = path.join(projectRoot, 'vendor', 'audio', 'soxr', 'build-manifest.json');
const runtimeRoot = path.join(projectRoot, '.tools', 'audio-codecs', 'windows-x64');
const runtimeDll = path.join(runtimeRoot, 'soxr.dll');
const stagingRoot = path.join(projectRoot, '.tools', 'dependency-staging', 'pcm-codecs');
const buildTempRoot = path.join(stagingRoot, 'soxr-zig-build-0.1.3');
const zigExe = path.join(projectRoot, '.tools', 'walkman', 'compiler', 'zig-x86_64-windows-0.15.2', 'zig.exe');
const sourceArchiveSha256 = 'b111c15fdc8c029989330ff559184198c161100a59312f5dc19ddeb9b5a15889';
const sourceArchiveUrl = 'https://downloads.sourceforge.net/project/soxr/soxr-0.1.3-Source.tar.xz';
const sourceArchiveName = 'soxr-0.1.3-Source.tar.xz';
const versionRoot = 'soxr-0.1.3-Source';
