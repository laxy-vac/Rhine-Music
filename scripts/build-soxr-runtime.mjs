const archivePath = path.join(projectRoot, '.tools', 'downloads', 'pcm-codecs', 'soxr-0.1.3-Source.tar.xz');
const sourceHome = path.join(projectRoot, 'vendor', 'audio', 'soxr', 'source');
const sourceRoot = path.join(sourceHome, 'soxr-0.1.3-Source');
