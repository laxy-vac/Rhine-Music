const upstreamBuildFiles = new Set([
  'CMakeLists.txt',
  'src/CMakeLists.txt',
  'LICENCE',
  'COPYING.LGPL',
  'NEWS',
  'README',
  'soxr-config.h.in',
]);
const sourceFilesToCompile = [
  'src/soxr.c',
  'src/data-io.c',
  'src/dbesi0.c',
  'src/filter.c',
  'src/fft4g64.c',
  'src/cr.c',
  'src/cr64.c',
];
